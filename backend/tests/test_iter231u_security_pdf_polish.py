# ─── Functional test — build the PDF and parse it ───────────────────


def test_render_security_pdf_emits_full_compliance_artifact():
    """Builds a real PDF with sample audits + meta and verifies the
    parsed text contains every compliance section."""
    from routes.admin_platform import _render_security_pdf
    audits = [
        {
            "iteration": "230m",
            "audited_at": "2026-02-27T10:00:00+00:00",
            "auditor": "QA Bot",
            "scope": "Iter 230m — Trade engine + waivers.",
            "verdict": "All findings remediated.",
            "findings": [
                {"id": "F-001", "severity": "high", "status": "fixed",
                 "title": "Token leak in trade response", "remediated_in": "iter230m"},
                {"id": "F-002", "severity": "med", "status": "fixed",
                 "title": "CSRF on revoke", "remediated_in": "iter230m"},
            ],
            "regression_tests": ["test_iter230m_trades.py"],
        },
        {
            "iteration": "230n",
            "audited_at": "2026-02-28T10:00:00+00:00",
            "auditor": "QA Bot",
            "scope": "Iter 230n — Notifications.",
            "verdict": "Clean.",
            "findings": [],
            "regression_tests": [],
        },
    ]
    totals = {"open": 0, "in_progress": 1, "fixed": 8}
    md = "## Threat Model\n\nSome content with `inline code`.\n\n- bullet one\n- bullet two\n"
    meta = {
        "generated_by_email": "compliance@dynastydreams.com",
        "previous_export": {
            "sha256": "abcdef1234" * 6 + "abcdef12",  # 64 hex chars
            "generated_at": "2026-02-26T10:00:00+00:00",
            "generated_by": "ops@dynastydreams.com",
        },
        "filename": "dynasty-dreams-security-20260228.pdf",
    }
    pdf_bytes = _render_security_pdf(
        audits=audits, totals=totals, md_text=md, meta=meta,
    )
    assert pdf_bytes.startswith(b"%PDF"), "Output must be a real PDF"

    # Parse and verify text.
    from pypdf import PdfReader
    import io
    reader = PdfReader(io.BytesIO(pdf_bytes))
    assert len(reader.pages) >= 3, f"Expected >=3 pages (cover + summary + timeline), got {len(reader.pages)}"
    text = "\n".join(p.extract_text() or "" for p in reader.pages)

    # ── Cover page ─────────────────────────────────────────────────
    assert "Dynasty Dreams" in text
    assert "Security Audit Bundle" in text
    assert "Document version" in text
    assert "Document owner" in text
    assert "Classification" in text
    assert "Retention" in text
    assert "7 years" in text
    assert "CONFIDENTIAL" in text
    assert "compliance@dynastydreams.com" in text  # generated_by
    assert "Previous export" in text
    assert "sha256:abcdef12" in text  # short sha shown
    # ── Executive Summary ──────────────────────────────────────────
    assert "Executive Summary" in text
    assert "closure rate" in text or "100%" in text or "89%" in text  # 8/(8+1+0) = 88.8%
    # ── Document Control ───────────────────────────────────────────
    assert "Document Control" in text
    # ── Audit Timeline ─────────────────────────────────────────────
    assert "Audit Timeline" in text
    assert "230m" in text
    assert "230n" in text
    # ── SECURITY.md content ────────────────────────────────────────
    assert "Threat Model" in text
    # ── Footer ─────────────────────────────────────────────────────
    assert "Page 1 of" in text
    assert "Dynasty Dreams Platform" in text  # footer banner


