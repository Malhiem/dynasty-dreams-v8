def test_numbered_canvas_emits_page_x_of_y_on_every_page():
    """Smoke-test: every page footer ends with 'Page N of TOTAL'."""
    from routes.admin_platform import _render_security_pdf
    # Build a doc with enough content to span multiple pages.
    audits = []
    for i in range(20):
        audits.append({
            "iteration": f"230{chr(97+i%26)}",
            "audited_at": f"2026-01-{(i%28)+1:02d}T10:00:00+00:00",
            "scope": "Long scope " * 20,
            "verdict": "Verdict text",
            "findings": [{"id": f"F-{j:03d}", "severity": "low", "status": "fixed",
                          "title": f"Finding {j}", "remediated_in": "iter230"} for j in range(5)],
        })
    pdf_bytes = _render_security_pdf(
        audits=audits, totals={"open": 0, "in_progress": 0, "fixed": 100},
        md_text="## Threat Model\n", meta={},
    )
    from pypdf import PdfReader
    import io
    reader = PdfReader(io.BytesIO(pdf_bytes))
    total = len(reader.pages)
    assert total >= 3, f"Expected multi-page PDF, got {total} pages"
    # Sample first + last page footers.
    first_text = reader.pages[0].extract_text() or ""
    last_text = reader.pages[-1].extract_text() or ""
    assert f"Page 1 of {total}" in first_text
    assert f"Page {total} of {total}" in last_text
