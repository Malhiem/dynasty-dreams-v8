import type { Page } from '@playwright/test';
export const selectors = (page: Page) => ({
  alert: () => page.getByRole("alert"),
  status: () => page.getByRole("status").filter({hasText:"Loading history"}),
  retry: () => page.getByRole("button", {name:"Retry",exact:true}),
  leaguePicker: () => page.getByTestId("current-league-dropdown-trigger"),
  leagueOption: (id: string) => page.getByTestId(`current-league-option-${id}`),
  championshipRecord: () => page.getByTestId("record-most-champs-card"),
  franchiseRecord: (year: number) => page.getByTestId(`franchise-record-${year}`),
  pointsHolder: (id: string, year: number) => page.getByTestId(`record-points-holder-${id}-${year}`),
  mvpAwardCard: () => page.getByTestId("player-award-season-mvp-—-hart-trophy"),
  awardCount: (id: string) => page.getByTestId(`player-award-count-${id}`),
  room: () => page.getByTestId('trophy-room-page'),
  years: () => page.getByTestId('trophy-room-year-filter'),
  all: () => page.getByTestId('filter-all'),
  recent: () => page.getByTestId('filter-recent'),
  teamRafters: () => page.getByTestId('team-banners-rafter'),
  leagueRafters: () => page.getByTestId('league-banners-rafter'),
  banner: (type: string, year: number) => page.getByTestId(`trophy-banner-${type}-${year}`),
  trophy: (label: string, year: number) => page.getByTestId(`trophy-item-${label}-${year}`),
  teamCard: (id: string) => page.getByTestId(`team-room-card-${id}`),
  exit: () => page.getByTestId('exit-team-room-btn'),
  rosterLink: () => page.getByTestId('roster-team-trophy-link'),
  rosterTab: () => page.getByTestId('roster-tab-trophy-room'),
  embedded: () => page.getByTestId('roster-trophy-room-content'),
  tab: (name: string) => page.getByRole('tab', { name, exact: true }),
  history: () => page.getByTestId('league-history-page'),
  panel: () => page.getByRole('tabpanel'),
  historyRow: (id: string) => page.getByTestId(`lifetime-row-${id}`),
  historyTeamRow: (name: string) => page.getByRole('row').filter({has: page.getByRole('link', {name, exact:true})}),
  teamPicker: (name: string) => page.getByRole('combobox').filter({hasText: name}),
});
